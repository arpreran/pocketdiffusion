"""No-reference image quality of every system on the 200-prompt test split.

Re-uses the images already generated by eval_quality (results/gen/coco_test/<system>/) and
adds NIQE (lower = more natural), PocketIQA and the artifact-flag rate, so the report's
"baseline vs deep-learning-only vs hybrid" table has perceptual columns for every row.
CPU only, no generation.

Usage: python -m eval.eval_iqa_test [--systems baseline turbo1_taesd pocketdiff]
"""
from __future__ import annotations

import argparse

from eval.common import GEN_DIR, RESULTS_DIR, coco_test, load_set, update_json
from eval.eval_ablation import iqa_stats

DEFAULT = ["baseline", "sd15_fp16_dpm20", "sd15_lcm4_taesd", "turbo1_taesd", "pocketdiff", "pocketdiff_fast"]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--systems", nargs="*", default=DEFAULT)
    args = ap.parse_args()
    rows = coco_test()
    for s in args.systems:
        if not (GEN_DIR / "coco_test" / s).exists():
            print(f"{s}: no images, run eval.eval_quality first")
            continue
        imgs, _, _ = load_set("coco_test", s, rows)
        res = {"n_images": len(imgs), **iqa_stats(imgs)}
        update_json(RESULTS_DIR / "iqa_test.json", s, res)
        print(f"{s:22s} n={len(imgs)}  NIQE {res['niqe']:.2f}  PocketIQA {res['pocket_iqa']:.1f}  "
              f"artifact rate {res['artifact_flag_rate']:.2f}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
