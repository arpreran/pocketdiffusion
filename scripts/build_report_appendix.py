"""Generate the report appendices from the repository's own data (no hand-typed numbers).

Writes everything between the APPENDIX:START / APPENDIX:END markers of Solution_Report_P3.md:
  A  full evaluation tables (tables of eval_P3_<TeamID>.md, sections 1-10)
  B  compositional benchmark: per-category results + all 58 annotated prompts
  C  device profiles used by the planner
  D  generation presets
  E  REST API of the backend
  F  automated tests
  G  hardware and software environment
  H  repository structure
Only headings, tables and code blocks are produced, so the report's AI-share count is unchanged.

Usage: python scripts/build_report_appendix.py
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
REPORT = ROOT / "Solution_Report_P3.md"
START = "<!-- APPENDIX:START (generated by scripts/build_report_appendix.py - do not edit by hand) -->"
END = "<!-- APPENDIX:END -->"
BOLD = re.compile(r"^\*\*(.+?)\*\*")


def eval_tables() -> list[str]:
    team = json.loads((ROOT / "team.json").read_text(encoding="utf-8"))
    src = ROOT / f"eval_P3_{team['team_id']}.md"
    out = ["### A. Full evaluation tables", "", "| Source | Generated by |", "|---|---|",
           f"| `{src.name}` | `python -m eval.make_report` |", ""]
    section, keep = None, False
    for line in src.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^## (\d+)\. (.+)", line)
        if m:
            keep = int(m.group(1)) <= 10
            if keep:
                out += ["", f"#### A.{m.group(1)} {m.group(2)}", ""]
            continue
        if keep and line.startswith("|"):
            out.append(line)
        elif keep and BOLD.match(line):
            out += ["", "##### " + BOLD.match(line).group(1), ""]
        elif keep and out and out[-1].startswith("|") and not line.startswith("|"):
            out.append("")
    return out


def compositional() -> list[str]:
    data = json.loads((ROOT / "prompts" / "compositional.json").read_text(encoding="utf-8"))
    items = data if isinstance(data, list) else data["prompts"]
    res = json.loads((ROOT / "results" / "compositional.json").read_text(encoding="utf-8"))
    systems = [("sd15_fp16", "Baseline SD1.5 50 steps"), ("pocketdiff", "PocketDiffusion"),
               ("pocketdiff_semantic8", "+ semantic re-rank N=8")]
    cats = []
    for it in items:
        if it["category"] not in cats:
            cats.append(it["category"])
    out = ["", "### B. Compositional benchmark (58 annotated prompts × 2 seeds)", "",
           "#### B.1 All-constraints rate per category", "",
           "| Category | Prompts | " + " | ".join(n for _, n in systems) + " |",
           "|---|---|" + "---|" * len(systems)]
    for c in cats:
        n = sum(1 for it in items if it["category"] == c)
        vals = [res.get(k, {}).get("per_category_all_ok", {}).get(c) for k, _ in systems]
        out.append(f"| {c} | {n} | " + " | ".join("–" if v is None else f"{100 * v:.0f} %" for v in vals) + " |")
    out += ["", "#### B.2 Prompts and annotations", "", "| ID | Category | Prompt | Objects (count, colour) | Relations |",
            "|---|---|---|---|---|"]
    for it in items:
        objs = ", ".join(f"{o['name']}" + (f" ×{o['count']}" if o.get("count", 1) > 1 else "") +
                         (f" ({o['color']})" if o.get("color") else "") for o in it["objects"])
        rels = ", ".join(f"{r['subject']} {r['relation'].replace('_', ' ')} {r['object']}" for r in it["relations"]) or "–"
        out.append(f"| {it['id']} | {it['category']} | {it['prompt']} | {objs} | {rels} |")
    return out


def devices_and_presets() -> list[str]:
    from pocketdiff.config import DEVICE_PROFILES, PRESETS
    out = ["", "### C. Device profiles used by the planner", "",
           "| Key | Profile | Kind | Memory budget | Assumed TFLOPS | Runs on |", "|---|---|---|---|---|---|"]
    for k, p in DEVICE_PROFILES.items():
        out.append(f"| `{k}` | {p.label} | {p.kind} | {p.memory_budget_mb:,.0f} MB | "
                   f"{p.eff_tflops if p.eff_tflops else '– (measured)'} | {p.run_device} |")
    out += ["", "### D. Generation presets", "",
            "| Preset | Family | Precision | Scheduler | Steps | CFG | LCM-LoRA | Decoder | Weights | Text encoder | Size |",
            "|---|---|---|---|---|---|---|---|---|---|---|"]
    for k, c in PRESETS.items():
        out.append(f"| `{k}` | {c.family} | {c.dtype} | {c.scheduler} | {c.steps} | {c.guidance} | "
                   f"{'yes' if c.lcm_lora else 'no'} | {c.vae} | {c.quant} | {c.text_encoder} | {c.width}×{c.height} |")
    return out


def api() -> list[str]:
    doc = (ROOT / "backend" / "main.py").read_text(encoding="utf-8").split('"""')[1]
    out = ["", "### E. REST API (FastAPI backend)", "", "| Method | Path | Purpose |", "|---|---|---|"]
    for line in doc.splitlines():
        m = re.match(r"^(GET|POST|DELETE|PUT)\s+(\S+)\s+(.+)$", line.strip())
        if m:
            out.append(f"| {m.group(1)} | `{m.group(2)}` | {m.group(3).strip()} |")
    return out


def tests() -> list[str]:
    py = sys.executable
    col = subprocess.run([py, "-m", "pytest", "--collect-only", "-q", "tests"], cwd=ROOT,
                         capture_output=True, text=True, timeout=600).stdout
    run = subprocess.run([py, "-m", "pytest", "-q", "tests"], cwd=ROOT, capture_output=True, text=True,
                         timeout=1200).stdout.strip().splitlines()
    names = [l.strip() for l in col.splitlines() if "::" in l]
    out = ["", "### F. Automated tests", "", "| Command | Result |", "|---|---|",
           f"| `python -m pytest -q tests` | `{run[-1] if run else 'not run'}` |", "",
           "| # | Test file | Test |", "|---|---|---|"]
    for i, n in enumerate(names, 1):
        f, t = n.split("::", 1)
        out.append(f"| {i} | `{f}` | `{t}` |")
    return out


def environment() -> list[str]:
    eff = json.loads((ROOT / "results" / "efficiency.json").read_text(encoding="utf-8")).get("_env", {})
    out = ["", "### G. Hardware and software environment", "", "| Item | Value |", "|---|---|",
           f"| GPU | {eff.get('gpu', '–')} (8 GB) |", f"| CPU | {eff.get('cpu', '–')} |",
           f"| PyTorch | {eff.get('torch', '–')} |", f"| Benchmarks measured | {eff.get('date', '–')} |"]
    for line in (ROOT / "requirements.txt").read_text(encoding="utf-8").splitlines():
        if "==" in line and not line.startswith("#"):
            name, ver = line.split("==", 1)
            out.append(f"| {name} | {ver} |")
    return out


def structure() -> list[str]:
    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    m = re.search(r"## Project layout\s+```\n(.*?)```", readme, re.S)
    return ["", "### H. Repository structure", "", "```", (m.group(1).rstrip() if m else ""), "```"]


def main() -> int:
    body = ["## Appendices", ""] + eval_tables() + compositional() + devices_and_presets() + api() + tests() + \
           environment() + structure()
    text = REPORT.read_text(encoding="utf-8")
    i, j = text.index(START), text.index(END)
    REPORT.write_text(text[:i + len(START)] + "\n\n" + "\n".join(body).strip() + "\n\n" + text[j:], encoding="utf-8")
    print(f"appendix: {len(body)} lines written to {REPORT.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
